# Generate local Zed / clangd configuration:
#   - build/clangd/compile_commands.json (Ninja + MSVC)
#   - .clangd in the repo root (adds MSVC / Windows SDK system include paths)
#
# Usage (from anywhere in the repo):
#   powershell -ExecutionPolicy Bypass -File tools/setup-clangd.ps1
#
# .clangd contains machine-specific absolute paths and is listed in .gitignore.

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

function Find-VisualStudio {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (-not (Test-Path $vswhere)) {
        throw 'vswhere.exe not found. Install the Visual Studio 2022 C++ desktop workload.'
    }
    $path = & $vswhere -latest -products * `
        -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 `
        -property installationPath
    if (-not $path) {
        throw 'MSVC x64 toolchain not found in Visual Studio.'
    }
    return $path.Trim()
}

function Find-LatestDirectory([string] $parent) {
    if (-not (Test-Path $parent)) { return $null }
    return Get-ChildItem $parent -Directory |
        Sort-Object Name -Descending |
        Select-Object -First 1
}

function To-ForwardSlash([string] $path) {
    return $path.Replace('\', '/')
}

function Find-VcPkg {
    $command = Get-Command vcpkg -ErrorAction SilentlyContinue
    if ($command) { return Split-Path -Parent $command.Source }
    if ($env:VCPKG_ROOT -and (Test-Path (Join-Path $env:VCPKG_ROOT 'vcpkg.exe'))) {
        return $env:VCPKG_ROOT
    }
    throw 'vcpkg not found. Add vcpkg to PATH or set VCPKG_ROOT.'
}

$vs = Find-VisualStudio
$msvc = Find-LatestDirectory (Join-Path $vs 'VC\Tools\MSVC')
if (-not $msvc) { throw 'MSVC tools directory not found.' }
$msvcInclude = Join-Path $msvc.FullName 'include'

$sdkRoot = Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\10\Include'
$sdk = Find-LatestDirectory $sdkRoot
if (-not $sdk) { throw "Windows SDK not found: $sdkRoot" }
$sdkInclude = $sdk.FullName

$vcpkgRoot = Find-VcPkg
$toolchain = Join-Path $vcpkgRoot 'scripts\buildsystems\vcpkg.cmake'
$installed = Join-Path $vcpkgRoot 'installed\x64-windows'
if (-not (Test-Path $toolchain)) { throw "vcpkg toolchain not found: $toolchain" }
if (-not (Test-Path (Join-Path $installed 'include'))) {
    throw 'vcpkg x64-windows packages not found. Run: vcpkg install wxwidgets:x64-windows'
}

$ninja = Get-Command ninja -ErrorAction SilentlyContinue
if (-not $ninja) {
    throw 'ninja not found. Install Ninja and add it to PATH (the Visual Studio copy works too).'
}

# 1. Configure a Ninja build that exports compile_commands.json.
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat'
$buildDir = Join-Path $root 'build\clangd'
$cmakeArgs = @(
    'cmake',
    '-S', "`"$root`"",
    '-B', "`"$buildDir`"",
    '-G', 'Ninja',
    '-DCMAKE_BUILD_TYPE=Release',
    "-DCMAKE_TOOLCHAIN_FILE=`"$toolchain`"",
    '-DVCPKG_TARGET_TRIPLET=x64-windows',
    '-DCMAKE_EXPORT_COMPILE_COMMANDS=ON'
) -join ' '

Write-Host 'Configuring build/clangd and exporting compile_commands.json ...'
cmd /c "call `"$vcvars`" >nul && $cmakeArgs"
if ($LASTEXITCODE -ne 0) { throw 'CMake configure failed.' }
if (-not (Test-Path (Join-Path $buildDir 'compile_commands.json'))) {
    throw 'compile_commands.json was not generated.'
}

# 2. Write .clangd with the system include paths clangd cannot get from cl.exe.
$lines = @(
    '# Generated by tools/setup-clangd.ps1 - machine-specific, do not commit.',
    'CompileFlags:',
    '  CompilationDatabase: build/clangd',
    '  Add:'
)
$includes = @(
    $msvcInclude,
    (Join-Path $sdkInclude 'ucrt'),
    (Join-Path $sdkInclude 'shared'),
    (Join-Path $sdkInclude 'um'),
    (Join-Path $sdkInclude 'winrt'),
    (Join-Path $sdkInclude 'cppwinrt')
)
foreach ($include in $includes) {
    $lines += "    - `"-I$(To-ForwardSlash $include)`""
}
$lines += @(
    '    - "-fms-extensions"',
    '    - "-fms-compatibility"',
    '    - "-fdelayed-template-parsing"',
    '  Remove:',
    '    - "/permissive-"',
    '    - "/MP"',
    '    - "/FS"',
    '    - "/utf-8"'
)
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllLines((Join-Path $root '.clangd'), $lines, $utf8)

Write-Host ''
Write-Host 'Done:'
Write-Host "  compile_commands.json : $buildDir\compile_commands.json"
Write-Host "  clangd config         : $root\.clangd"
Write-Host 'Restart Zed or run "clangd: Restart language server".'
